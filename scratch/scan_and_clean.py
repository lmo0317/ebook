COMPILED_RULES = [(re.compile(p), r) for p, r in RULES]

def clean_text(text: str) -> str:
    if not text:
        return text
    t = text
    for pat, repl in COMPILED_RULES:
        t = pat.sub(repl, t)
    return t

if __name__ == "__main__":
    db_path = r"output\한 권으로 끝내는 실전 LLM 파인튜닝\reader.db"
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()
    
    cur.execute("SELECT id, page, `order`, original, edited FROM Paragraph ORDER BY page, `order`")
    rows = cur.fetchall()
    
    print(f"Total paragraphs to inspect: {len(rows)}")
    modified_count = 0
    
    for row_id, p, order, orig, ed in rows:
        current = ed if ed else orig
        cleaned = clean_text(current)
        if cleaned != current:
            cur.execute("UPDATE Paragraph SET edited=? WHERE id=?", (cleaned, row_id))
            modified_count += 1
            if modified_count <= 10 or (p in [123, 127, 261]):
                print(f"[P.{p}] Modified:")
                print(f"  OLD: {current[:80]}...")
                print(f"  NEW: {cleaned[:80]}...\n")
                
    conn.commit()
    conn.close()
    print(f"=== FINISHED DEEP CLEAN ===")
    print(f"Total modified paragraphs: {modified_count} / {len(rows)} ({modified_count/len(rows)*100:.1f}%)")
